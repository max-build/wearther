import type { ResolvedLocation } from "./locations.js";
import type { OutfitStyle } from "./outfit.js";
import type { WeatherReading } from "./weather.js";

/** Everything needed to show a finished recommendation again, byte for byte. */
export interface Recommendation {
  location: ResolvedLocation;
  weather: WeatherReading;
  text: string;
  model: string;
  usedFallback: boolean;
}

/** Handle returned to the request that is generating a recommendation. */
export interface Generation {
  resolve(rec: Recommendation): void;
  /** Call if generation did not finish. Safe to call after resolve() (no-op). */
  fail(): void;
}

/**
 * Remembers finished recommendations per (city, outfit style) for a fixed time,
 * measured from when each was first generated (hits do not extend it).
 *
 * Repeat requests are answered from here with no Open-Meteo or Claude call.
 * If an identical request is already being generated, later requests wait for
 * it instead of starting a second Claude call. Only complete, successful
 * results are stored: errors, refusals and abandoned requests are never cached.
 */
export class RecommendationCache {
  private readonly done = new Map<string, { value: Recommendation; expires: number }>();
  private readonly pending = new Map<string, Promise<Recommendation>>();

  constructor(
    private readonly ttlMs: number,
    private readonly maxEntries = 2000,
  ) {}

  static key(cityId: string, style: OutfitStyle): string {
    return `${cityId}|${style}`;
  }

  /** A finished, still-fresh recommendation, if there is one. */
  get(key: string): Recommendation | undefined {
    const hit = this.done.get(key);
    if (!hit) return undefined;
    if (hit.expires <= Date.now()) {
      this.done.delete(key);
      return undefined;
    }
    return hit.value;
  }

  /** If an identical request is mid-generation, waits for it. Resolves undefined if it fails. */
  async waitForPending(key: string): Promise<Recommendation | undefined> {
    const p = this.pending.get(key);
    if (!p) return undefined;
    return p.catch(() => undefined);
  }

  /** Marks `key` as being generated by the caller. */
  begin(key: string): Generation {
    let resolve!: (rec: Recommendation) => void;
    let reject!: (err: Error) => void;
    const promise = new Promise<Recommendation>((res, rej) => {
      resolve = res;
      reject = rej;
    });
    promise.catch(() => {}); // a failure with nobody waiting must not be an unhandled rejection
    this.pending.set(key, promise);

    let settled = false;
    const settle = () => {
      settled = true;
      if (this.pending.get(key) === promise) this.pending.delete(key);
    };
    return {
      resolve: (rec) => {
        if (settled) return;
        settle();
        this.store(key, rec);
        resolve(rec);
      },
      fail: () => {
        if (settled) return;
        settle();
        reject(new Error("generation did not complete"));
      },
    };
  }

  private store(key: string, value: Recommendation): void {
    const now = Date.now();
    this.done.set(key, { value, expires: now + this.ttlMs });
    if (this.done.size <= this.maxEntries) return;
    for (const [k, e] of this.done) if (e.expires <= now) this.done.delete(k);
    // Map keeps insertion order, so the first keys are the oldest.
    while (this.done.size > this.maxEntries) {
      const oldest = this.done.keys().next().value;
      if (oldest === undefined) break;
      this.done.delete(oldest);
    }
  }
}
